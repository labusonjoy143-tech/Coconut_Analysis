"""## 10. Forecast monthly total harvest

Forecasting uses the time dimension rather than a random split. Records are aggregated to one total per calendar month across barangays. A chronological holdout evaluates the final portion of the series. The code compares a seasonal-naive baseline with an exponential-smoothing model when available. Forecasts are for total harvest and should be interpreted cautiously if the historical series has gaps, structural changes, or too few years.
"""

from sklearn.metrics import mean_absolute_error, mean_squared_error
try:
    from statsmodels.tsa.holtwinters import ExponentialSmoothing
    HAS_STATSMODELS = True
except Exception as e:
    HAS_STATSMODELS = False
    print("statsmodels unavailable; seasonal-naive forecast will still run.", e)

month_lookup = {m: i for i, m in enumerate(
    ["January","February","March","April","May","June","July","August","September","October","November","December"], 1
)}
