forecast_df["Year"] = pd.to_numeric(forecast_df["Year"], errors="coerce")
forecast_df["Month Number"] = forecast_df["Month"].astype("string").str.title().map(month_lookup)
forecast_df[TARGET] = pd.to_numeric(forecast_df[TARGET], errors="coerce")
forecast_df = forecast_df.dropna(subset=["Year", "Month Number", TARGET])
forecast_df["Date"] = pd.to_datetime({
    "year": forecast_df["Year"].astype(int),
    "month": forecast_df["Month Number"].astype(int),
    "day": 1
})
monthly = forecast_df.groupby("Date")[TARGET].sum().sort_index().asfreq("MS")
# Missing months are left missing initially; time-series models require regular observations.
missing_months = int(monthly.isna().sum())
print("Monthly observations:", len(monthly), "| Missing calendar months:", missing_months)
monthly = monthly.interpolate(method="time", limit_direction="both")
