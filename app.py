plt.ylabel("Harvest (kg)")
plt.tight_layout()
plt.show()

if len(monthly) < 18:
    print("Warning: fewer than 18 monthly observations; seasonal forecasting may be unreliable.")
test_size = max(3, int(round(len(monthly) * 0.2)))
test_size = min(test_size, max(1, len(monthly) - 6))
train_ts, test_ts = monthly.iloc[:-test_size], monthly.iloc[-test_size:]

# Seasonal-naive: use the value from 12 months earlier when available; otherwise training median.
seasonal_naive = []
for date in test_ts.index:
    lag_date = date - pd.DateOffset(months=12)
    if lag_date in train_ts.index:
        seasonal_naive.append(float(train_ts.loc[lag_date]))
    else:
        seasonal_naive.append(float(train_ts.median()))
forecast_metrics = [{
    "model": "Seasonal-naive (12-month lag)",
    "MAE": mean_absolute_error(test_ts, seasonal_naive),
    "RMSE": mean_squared_error(test_ts, seasonal_naive) ** 0.5
}]
best_forecast = np.asarray(seasonal_naive)
best_forecast_name = "Seasonal-naive (12-month lag)"

if HAS_STATSMODELS and len(train_ts) >= 24:
    try:
        ets = ExponentialSmoothing(
            train_ts, trend="add", seasonal="add", seasonal_periods=12,
            initialization_method="estimated"
        ).fit(optimized=True)
        ets_pred = ets.forecast(len(test_ts))
        forecast_metrics.append({
            "model": "Exponential Smoothing (additive trend/seasonality)",
            "MAE": mean_absolute_error(test_ts, ets_pred),
            "RMSE": mean_squared_error(test_ts, ets_pred) ** 0.5
        })
        if forecast_metrics[-1]["MAE"] < forecast_metrics[0]["MAE"]:
            best_forecast = np.asarray(ets_pred)
            best_forecast_name = forecast_metrics[-1]["model"]
    except Exception as e:
        print("Exponential smoothing failed; retaining seasonal-naive baseline:", e)

forecast_comparison = pd.DataFrame(forecast_metrics).sort_values("MAE")
